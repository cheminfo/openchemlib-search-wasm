import { useEffect, useMemo, useState } from 'react';

import type { Corpus } from '../corpus.ts';
import { readIdCode } from '../corpus.ts';
import { integer, share } from '../format.ts';

import { depictMatch } from './depict.ts';
import type { FunctionKey } from './dictionary.ts';
import type { ExamplesSearcher, ExamplesState } from './examples.ts';

const SHOWN = 12;

interface ExamplesProps {
  functionKey: FunctionKey;
  corpus: Corpus | null;
  searcher: ExamplesSearcher | null;
  /** Why there is no corpus, when there is none. */
  corpusError: string | null;
  /** How many molecules the 1M frequency was measured on. */
  molecules: number;
}

/**
 * The key run over the dev corpus with the WebAssembly search: how often it matches there, next to
 * its 1M frequency, and the first matches drawn with the matched atoms shaded.
 * @param props - The key, the corpus and the searcher.
 * @returns The examples panel.
 */
export function Examples(props: ExamplesProps) {
  const { functionKey, corpus, searcher, corpusError, molecules } = props;
  const [state, setState] = useState<ExamplesState | null>(null);

  useEffect(() => {
    if (!searcher) return undefined;
    searcher.search(functionKey.fragments, SHOWN, setState);
    return () => {
      searcher.cancel();
    };
  }, [searcher, functionKey]);

  if (corpusError !== null) return <p className="muted">{corpusError}</p>;
  if (!corpus || !state) return <p className="muted">Loading the corpus…</p>;
  return (
    <div>
      <p className="label">
        {state.done ? 'found in' : 'scanning'} {integer(state.scanned)} of{' '}
        {integer(state.total)} corpus molecules: {integer(state.matched)}{' '}
        matches ({share(state.matched, Math.max(1, state.scanned))}) — on 1M:{' '}
        {share(functionKey.count1m, molecules)}
      </p>
      {state.error === null ? null : <p className="error">{state.error}</p>}
      <ExampleGrid
        corpus={corpus}
        indexes={state.examples}
        fragments={functionKey.fragments}
        prefix={functionKey.id}
      />
    </div>
  );
}

interface ExampleGridProps {
  corpus: Corpus;
  indexes: number[];
  fragments: string[];
  prefix: string;
}

// Every report from the workers hands over a new list of the same indexes: a drawing is made once.
const drawn = new Map<string, string>();

function ExampleGrid({ corpus, indexes, fragments, prefix }: ExampleGridProps) {
  const drawings = useMemo(() => {
    const safe = prefix.replaceAll(/[^\w-]/g, '_');
    if (drawn.size > 2000) drawn.clear();
    return indexes.map((index) => {
      const id = `ex-${safe}-${index}`;
      let svg = drawn.get(id);
      if (svg === undefined) {
        svg = depictMatch(readIdCode(corpus, index), fragments, id);
        drawn.set(id, svg);
      }
      return { index, svg };
    });
  }, [corpus, indexes, fragments, prefix]);
  if (drawings.length === 0) return null;
  return (
    <div className="drawings">
      {drawings.map(({ index, svg }) => (
        <figure key={index} className="drawing">
          {/* The SVG is generated by openchemlib-js from an idcode of our own corpus. */}
          <div dangerouslySetInnerHTML={{ __html: svg }} />
          <figcaption className="muted">#{integer(index)}</figcaption>
        </figure>
      ))}
    </div>
  );
}
