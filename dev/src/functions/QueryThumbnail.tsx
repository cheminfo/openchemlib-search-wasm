import { useEffect, useRef, useState } from 'react';

import { depictThumbnail } from './depict.ts';

const WIDTH = 136;
const HEIGHT = 88;

// A row scrolled out and back in keeps its drawing, and 3,611 rows are never all drawn at once.
const drawn = new Map<string, string>();

interface QueryThumbnailProps {
  /** The key's id, which names the drawing on the page. */
  id: string;
  /** The fragment to draw: the key's first. */
  idCode: string;
  /** How many more fragments the key is the OR of. */
  more: number;
}

/**
 * A key's query drawn the size of a list row, once the row comes near the screen: drawing every
 * key of the list up front would take seconds.
 * @param props - The key and its first fragment.
 * @returns The drawing, or its empty frame until the row is near.
 */
export function QueryThumbnail(props: QueryThumbnailProps) {
  const { id, idCode, more } = props;
  const frame = useRef<HTMLSpanElement>(null);
  const [svg, setSvg] = useState(() => drawn.get(id) ?? '');

  useEffect(() => {
    const target = frame.current;
    if (svg || !target) return undefined;
    const observer = new IntersectionObserver(
      (entries) => {
        if (!entries.some((entry) => entry.isIntersecting)) return;
        observer.disconnect();
        const made = depictThumbnail(
          idCode,
          `th-${id.replaceAll(/[^\w-]/g, '_')}`,
          WIDTH,
          HEIGHT,
        );
        drawn.set(id, made);
        setSvg(made);
      },
      { rootMargin: '600px' },
    );
    observer.observe(target);
    return () => {
      observer.disconnect();
    };
  }, [id, idCode, svg]);

  return (
    <span ref={frame} className="thumbnail">
      {/* The SVG is generated by openchemlib-js from the key's own idcode. */}
      {svg ? <span dangerouslySetInnerHTML={{ __html: svg }} /> : null}
      {more > 0 ? (
        <span className="more" title={`and ${more} more fragments`}>
          +{more}
        </span>
      ) : null}
    </span>
  );
}
