// Build step (Node-only): read the .wasm, gzip it, base64-encode it, and write a
// JS module exporting the constant. This mirrors cheminfo/inchi-js: the published
// package ships no binary file — the wasm travels embedded in JS, so it works the
// same from npm, a bundler, or a CDN, with no asset-loading story.
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = join(import.meta.dirname, '..');
const wasm = await readFile(join(root, 'target', 'wasm-gc', 'spike.wasm'));
const gz = gzipSync(wasm, { level: 9 });
const base64 = gz.toString('base64');

const out = join(root, 'node', 'wasm-data.mjs');
await writeFile(
  out,
  `// Generated by build/embed-wasm.mjs — do not edit.\nexport const wasmGzipBase64 = '${base64}';\n`,
);

// eslint-disable-next-line no-console
console.log(
  `embedded: wasm ${wasm.length} B -> gzip ${gz.length} B -> base64 ${base64.length} chars ` +
    `(${((base64.length / wasm.length) * 100).toFixed(0)}% of raw wasm)`,
);
