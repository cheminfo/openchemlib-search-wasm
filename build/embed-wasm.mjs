// Build step: embed the WasmGC module produced by `npm run build-wasm` into a JavaScript module as
// gzip+base64 (the cheminfo/inchi-js distribution pattern), and copy the TeaVM ESM runtime next to
// it.
//
// The outputs land in `wasm/` and are COMMITTED, as cheminfo/inchi-js commits its own embedded
// module. The TeaVM build is byte-reproducible, so CI can rebuild and diff to prove they match the
// Java source — which means the everyday `npm ci && npm test` needs no JDK and no Maven, and only a
// maintainer bumping OpenChemLib ever runs the Java toolchain.
//
// The payload is emitted as .js + .d.ts rather than .ts so that `tsc --project tsconfig.build.json`
// can compile src/ to lib/ without pulling a 160 kB string literal through the type checker: the
// relative path from lib/wasm/load.js and from src/wasm/load.ts is the same, so both resolve here.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = join(import.meta.dirname, '..');
const wasmDir = join(root, 'java', 'target', 'wasm-gc');
const outDir = join(root, 'wasm');

await mkdir(outDir, { recursive: true });

// `openchemlib.opt.wasm` is TeaVM's module after the binaryen pass `scripts/build-wasm.mjs` runs;
// the unoptimized `openchemlib.wasm` stays on disk as the benchmark's baseline and is never shipped.
const wasm = await readFile(join(wasmDir, 'openchemlib.opt.wasm'));
const gz = gzipSync(wasm, { level: 9 });
const base64 = gz.toString('base64');

await writeFile(
  join(outDir, 'data.js'),
  `// Generated by build/embed-wasm.mjs — do not edit.\nexport const wasmGzipBase64 =\n  '${base64}';\n`,
);
await writeFile(
  join(outDir, 'data.d.ts'),
  '// Generated by build/embed-wasm.mjs — do not edit.\nexport declare const wasmGzipBase64: string;\n',
);
await copyFile(
  join(wasmDir, 'openchemlib.wasm-runtime.js'),
  join(outDir, 'runtime.js'),
);
// The runtime is generated JS; ship the hand-written type declaration alongside it so
// `import { load } from '../../dist/runtime.js'` is typed.
await copyFile(
  join(root, 'build', 'runtime.d.ts'),
  join(outDir, 'runtime.d.ts'),
);

console.log(
  `embedded: wasm ${wasm.length} B -> gzip ${gz.length} B -> base64 ${base64.length} chars`,
);
