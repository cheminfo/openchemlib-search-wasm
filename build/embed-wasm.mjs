// Build step: embed the WasmGC module produced by `npm run build-wasm` into the
// TypeScript source as gzip+base64 (the cheminfo/inchi-js distribution pattern),
// and copy the TeaVM ESM runtime next to it. Both outputs are committed so the
// published package needs no separate binary asset and works in Node + browser.
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = join(import.meta.dirname, '..');
const wasmDir = join(root, 'java', 'target', 'wasm-gc');
const outDir = join(root, 'src', 'wasm');

const wasm = await readFile(join(wasmDir, 'openchemlib.wasm'));
const gz = gzipSync(wasm, { level: 9 });
const base64 = gz.toString('base64');

await writeFile(
  join(outDir, 'data.ts'),
  `// Generated by build/embed-wasm.mjs — do not edit.\n/* eslint-disable */\nexport const wasmGzipBase64 =\n  '${base64}';\n`,
);
await copyFile(join(wasmDir, 'openchemlib.wasm-runtime.js'), join(outDir, 'runtime.js'));

// eslint-disable-next-line no-console
console.log(
  `embedded: wasm ${wasm.length} B -> gzip ${gz.length} B -> base64 ${base64.length} chars`,
);
