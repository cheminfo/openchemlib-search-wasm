// Build step: bundle the ASCII parameter tables (force field, predictors,
// torsion data) into a JSON object keyed by their /resources/... path, then embed
// it gzip+base64 into the TypeScript source. Registered during
// loadOCL({ resources: true }).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

const resourcesToBundle = [
  'cod/bondLengthData.txt',
  'cod/torsionAngle.txt',
  'cod/torsionFrequency.txt',
  'cod/torsionID.txt',
  'cod/torsionRange.txt',
  'forcefield/mmff94/94s/outofplane.csv',
  'forcefield/mmff94/94s/torsionPlus.csv',
  'forcefield/mmff94/94s/torsion.csv',
  'forcefield/mmff94/angle.csv',
  'forcefield/mmff94/atom.csv',
  'forcefield/mmff94/bci.csv',
  'forcefield/mmff94/bndk.csv',
  'forcefield/mmff94/bond.csv',
  'forcefield/mmff94/covrad.csv',
  'forcefield/mmff94/def.csv',
  'forcefield/mmff94/dfsb.csv',
  'forcefield/mmff94/herschbachlaurie.csv',
  'forcefield/mmff94/outofplane.csv',
  'forcefield/mmff94/pbci.csv',
  'forcefield/mmff94/stbn.csv',
  'forcefield/mmff94/torsion.csv',
  'forcefield/mmff94/vanderwaals.csv',
  'druglikenessNoIndex.txt',
  'toxpredictor/i1.txt',
  'toxpredictor/i2.txt',
  'toxpredictor/i3.txt',
  'toxpredictor/m1.txt',
  'toxpredictor/m2.txt',
  'toxpredictor/m3.txt',
  'toxpredictor/r1.txt',
  'toxpredictor/r2.txt',
  'toxpredictor/r3.txt',
  'toxpredictor/t1.txt',
  'toxpredictor/t2.txt',
  'toxpredictor/t3.txt',
];

const root = join(import.meta.dirname, '..');
const source = join(root, 'resources');

const bundle = {};
for (const name of resourcesToBundle) {
  bundle[`/resources/${name}`] = readFileSync(join(source, name), 'utf8');
}

const json = JSON.stringify(bundle);
const gz = gzipSync(Buffer.from(json, 'utf8'), { level: 9 });
writeFileSync(
  join(root, 'src', 'wasm', 'resources.ts'),
  `// Generated by build/embed-resources.mjs — do not edit.\n/* eslint-disable */\nexport const resourcesGzipBase64 =\n  '${gz.toString('base64')}';\n`,
);

// eslint-disable-next-line no-console
console.log(
  `bundled ${resourcesToBundle.length} resources: json ${json.length} B -> gzip ${gz.length} B`,
);
